# Replace the installed Neovim config with the repo's, staged first so a failure leaves the old one.
# shellcheck disable=SC2154 # globals come from files install.sh sources earlier
step 'Neovim config'
source_config="$DOTFILES_ROOT/config/nvim"
config="${XDG_CONFIG_HOME:-$HOME/.config}/nvim"
[[ -d "$source_config" && ! -L "$source_config" && -f "$source_config/init.lua" ]] ||
  die "Missing repo Neovim config: $source_config"
mkdir -p "$(dirname "$config")"
_dotfiles_stage_dir=$(mktemp -d "${config}.install.XXXXXX")
readonly _dotfiles_stage_dir
printf '%s\n' "$_dotfiles_cleanup_owner" > "$_dotfiles_stage_dir/.dotfiles-installer-owner"
cp -Rp "$source_config" "$_dotfiles_stage_dir/nvim"
# Where this repo is, for lua/plugins/scout.lua (it loads scout from modules/scout here).
printf '%s\n' '-- Generated by dotfiles install.sh: the dotfiles folder this config came from.' \
  "return [==[$DOTFILES_ROOT]==]" > "$_dotfiles_stage_dir/nvim/lua/dotfiles_root.lua"
rm -rf -- "$config"
mv "$_dotfiles_stage_dir/nvim" "$config"
ok "replaced $(short_path "$config")"
